// @vitest-environment jsdom
import { afterEach, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import Editor from './Editor'

afterEach(() => { cleanup(); vi.unstubAllGlobals() })
it('does not inline-edit protected cards even when their text matches site copy', async () => {
  vi.stubGlobal('fetch', vi.fn(async () => Response.json({ mode: 'text', content: { home: { hero: { titleLine: 'Shared text' } }, catalog: { title: 'Shared text' } }, revisions: {}, token: 'local-token' })))
  render(<Editor />)
  await screen.findByText('Double-click text to edit. Switch to Browse to navigate.')
  const frame = screen.getByTitle('Bookstore live preview') as HTMLIFrameElement
  frame.contentDocument!.open()
  frame.contentDocument!.write('<!doctype html><html><head></head><body><article class="book-card"><h2>Shared text</h2></article></body></html>')
  frame.contentDocument!.close()
  fireEvent.load(frame)
  fireEvent.doubleClick(frame.contentDocument!.querySelector('h2')!)
  await screen.findByText(/content is protected/)
  expect(frame.contentDocument!.querySelector('textarea')).toBeNull()
})
it('shows curation controls without text-editing controls in content mode', async () => {
  vi.stubGlobal('fetch', vi.fn(async () => Response.json({ mode: 'content', content: {}, revisions: {}, token: 'local-token', publishing: { enabled: true, repository: 'content' } })))
  render(<Editor />)
  const publish = await screen.findByRole('button', { name: 'Publish & exit' })
  expect(publish.closest('.editor-header')).toBeTruthy()
  expect(screen.getByRole('heading', { name: /What would you like/ })).toBeTruthy()
  for (const name of ['Homepage', 'Coupons', 'New journal', 'New reading list']) expect(screen.getByRole('button', { name }).closest('.content-dashboard')).toBeTruthy()
  expect(screen.queryByTitle('Bookstore live preview')).toBeNull()
  expect(screen.queryByRole('group', { name: 'Preview size' })).toBeNull()
  expect(screen.queryByRole('button', { name: 'Save' })).toBeNull()
  expect(screen.queryByRole('button', { name: 'Fields' })).toBeNull()
})
it('opens a workspace from the content dashboard and returns when it closes', async () => {
  vi.stubGlobal('fetch', vi.fn(async () => Response.json({ mode: 'content', content: { catalog: { books: [] }, journal: { articles: [] } }, revisions: {}, token: 'local-token' })))
  render(<Editor />)
  fireEvent.click(await screen.findByRole('button', { name: 'New journal' }))
  expect(screen.getByRole('dialog', { name: 'New journal entry' })).toBeTruthy()
  expect(screen.getByTitle('Unsaved editorial preview')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'Discard draft' }))
  expect(screen.queryByRole('dialog')).toBeNull()
  expect(screen.getByRole('heading', { name: /What would you like/ })).toBeTruthy()
})
it('requires confirmation before publishing and shows a safe completion screen', async () => {
  const fetchMock = vi.fn(async (url: string) => url.endsWith('/publish')
    ? Response.json({ revision: 'abc123' })
    : Response.json({ content: {}, revisions: {}, token: 'local-token', publishing: { enabled: true, repository: 'https://github.com/example/content.git' } }))
  vi.stubGlobal('fetch', fetchMock)
  render(<Editor />)
  fireEvent.click(await screen.findByRole('button', { name: 'Publish & exit' }))
  expect(fetchMock).toHaveBeenCalledTimes(1)
  fireEvent.click(screen.getByRole('button', { name: 'Confirm publish & exit' }))
  await screen.findByText(/Published commit abc123/)
  expect(fetchMock.mock.calls[1][0]).toBe('/__editor/api/publish')
  expect(screen.queryByRole('button', { name: 'Save' })).toBeNull()
})
it('retains the editor when publishing fails', async () => {
  vi.stubGlobal('fetch', vi.fn(async (url: string) => url.endsWith('/publish')
    ? Response.json({ error: 'Remote content changed. Local edits retained.' }, { status: 400 })
    : Response.json({ content: {}, revisions: {}, token: 'local-token', publishing: { enabled: true, repository: 'https://github.com/example/content.git' } })))
  render(<Editor />)
  fireEvent.click(await screen.findByRole('button', { name: 'Publish & exit' }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirm publish & exit' }))
  await screen.findByText('Remote content changed. Local edits retained.')
  expect(screen.getByRole('button', { name: 'Publish & exit' })).toBeTruthy()
})
it('edits preview text inline without saving until requested and offers a mobile viewport', async () => {
  const fetchMock = vi.fn(async () => Response.json({ content: { home: { hero: { titleLine: 'Good books.' } } }, revisions: { home: 'version' }, token: 'local-token' }))
  vi.stubGlobal('fetch', fetchMock)
  render(<Editor />)
  await screen.findByText('Double-click text to edit. Switch to Browse to navigate.')
  expect(screen.queryByRole('button', { name: 'New journal' })).toBeNull()
  const frame = screen.getByTitle('Bookstore live preview') as HTMLIFrameElement
  frame.contentDocument!.open()
  frame.contentDocument!.write('<!doctype html><html><head></head><body><h1>Good books.</h1></body></html>')
  frame.contentDocument!.close()
  fireEvent.load(frame)
  const heading = frame.contentDocument!.querySelector('h1')!
  fireEvent.doubleClick(heading)
  await screen.findByLabelText('home.json · hero.titleLine')
  const inline = frame.contentDocument!.querySelector('textarea')!
  expect(inline).toBeTruthy()
  fireEvent.input(inline, { target: { value: 'Great books.' } })
  await waitFor(() => expect(heading.textContent).toBe('Great books.'))
  expect((screen.getByRole('button', { name: 'Save (1)' }) as HTMLButtonElement).disabled).toBe(false)
  expect(fetchMock).toHaveBeenCalledTimes(1)
  fireEvent.click(screen.getByRole('button', { name: 'Mobile · 390px' }))
  expect(frame.parentElement?.classList.contains('editor-mobile')).toBe(true)
  fireEvent.click(screen.getByRole('button', { name: 'Reset this field' }))
  await waitFor(() => expect(heading.textContent).toBe('Good books.'))
})
